-- ----------------------------------------------------
-- UNIQUE UID CONSTRAINTS (Block Duplicate Registrations)
-- ----------------------------------------------------
DO $$ 
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'day1_uid_unique'
    ) THEN
        ALTER TABLE public.day1_registrations ADD CONSTRAINT day1_uid_unique UNIQUE (uid);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'day2_uid_unique'
    ) THEN
        ALTER TABLE public.day2_registrations ADD CONSTRAINT day2_uid_unique UNIQUE (uid);
    END IF;
END $$;

-- ----------------------------------------------------
-- ROW LEVEL SECURITY (RLS) & POLICIES
-- ----------------------------------------------------
ALTER TABLE public.day1_registrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.day2_registrations ENABLE ROW LEVEL SECURITY;

-- Allow anyone to register (Public INSERT)
DO $$ 
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Allow public insert to day1'
    ) THEN
        CREATE POLICY "Allow public insert to day1" ON public.day1_registrations FOR INSERT WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Allow public insert to day2'
    ) THEN
        CREATE POLICY "Allow public insert to day2" ON public.day2_registrations FOR INSERT WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Allow authenticated read to day1'
    ) THEN
        CREATE POLICY "Allow authenticated read to day1" ON public.day1_registrations FOR SELECT USING (auth.role() = 'authenticated');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Allow authenticated read to day2'
    ) THEN
        CREATE POLICY "Allow authenticated read to day2" ON public.day2_registrations FOR SELECT USING (auth.role() = 'authenticated');
    END IF;
END $$;

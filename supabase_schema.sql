-- 0. CREATE REGISTRATION SEQUENCES (for auto-generating EGT2-P-0001 / EGT2-T-0001)
CREATE SEQUENCE IF NOT EXISTS day1_reg_seq START WITH 1;
CREATE SEQUENCE IF NOT EXISTS day2_reg_seq START WITH 1;

-- 1. CREATE DAY 1 REGISTRATIONS TABLE (STAGE ARENA - SOLO & GROUP ACTS)
CREATE TABLE IF NOT EXISTS public.day1_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_id VARCHAR(50) UNIQUE DEFAULT ('EGT2-P-' || LPAD(CAST(nextval('day1_reg_seq'::regclass) AS TEXT), 4, '0')),
    full_name TEXT NOT NULL,
    uid VARCHAR(50) NOT NULL UNIQUE,
    email TEXT NOT NULL,
    phone VARCHAR(20) NOT NULL,
    department TEXT DEFAULT 'AIT CSE',
    academic_year TEXT DEFAULT '3rd Year',
    section TEXT NOT NULL,
    group_name TEXT NOT NULL,
    block TEXT NOT NULL,
    category TEXT NOT NULL,
    requires_audio_track TEXT DEFAULT 'No',
    audio_track_url TEXT,
    entry_type TEXT DEFAULT 'Solo',
    team_name TEXT,
    team_members TEXT,
    team_members_raw TEXT,
    performance_desc TEXT,
    previous_performance_link TEXT,
    instagram TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CREATE DAY 2 REGISTRATIONS TABLE (TECH WIZARDS ARENA - SQUADS)
CREATE TABLE IF NOT EXISTS public.day2_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_id VARCHAR(50) UNIQUE DEFAULT ('EGT2-T-' || LPAD(CAST(nextval('day2_reg_seq'::regclass) AS TEXT), 4, '0')),
    leader_name TEXT NOT NULL,
    uid VARCHAR(50) NOT NULL UNIQUE,
    email TEXT NOT NULL,
    phone VARCHAR(20) NOT NULL,
    department TEXT DEFAULT 'AIT CSE',
    academic_year TEXT DEFAULT '3rd Year',
    section TEXT NOT NULL,
    group_name TEXT NOT NULL,
    block TEXT NOT NULL,
    squad_name TEXT NOT NULL,
    
    -- Combined Teammate Strings
    teammate_1 TEXT NOT NULL,
    teammate_2 TEXT NOT NULL,
    teammate_3 TEXT DEFAULT '',
    
    -- Separated Teammate Fields (Name, UID, Section, Group, Block)
    teammate_1_name TEXT,
    teammate_1_uid VARCHAR(50),
    teammate_1_section TEXT,
    teammate_1_group TEXT,
    teammate_1_block TEXT,

    teammate_2_name TEXT,
    teammate_2_uid VARCHAR(50),
    teammate_2_section TEXT,
    teammate_2_group TEXT,
    teammate_2_block TEXT,

    teammate_3_name TEXT,
    teammate_3_uid VARCHAR(50),
    teammate_3_section TEXT,
    teammate_3_group TEXT,
    teammate_3_block TEXT,
    
    created_at TIMESTAMPTZ DEFAULT NOW()
);

